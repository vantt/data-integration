"""Golden snapshot: prove a change leaves every public table's data identical.

Evolved from the order-independent mart checksum used when the std layer was introduced,
extended with row-level fingerprints, staleness checks and keyed diffs.

Run it inside a shadow container (scripts/shadow/run-shadow.sh) so it reads shadow lakes
only. Subcommands:

  init --manifest M --out public_models.yaml
      Generate the public table list: every model whose config.location writes to
      rolling/ (served via serving/olap.duckdb, Metabase, Rill, Evidence) plus the
      non-rolling relations read by CRM/tools (EXTRA_RELATIONS). Keys come from
      unique / unique_combination_of_columns tests.

  capture --lake DIR --models public_models.yaml --out snapshot.json
      Fingerprint every public table of one lake. Fails when a table is stale: its newest
      rolling parquet is older than <lake>/_shadow_meta/build_start, or its node is not
      `success` in <lake>/_shadow_meta/run_results.json.

  compare A.json B.json
      Exit 1 and print each difference (rows, schema, per-column, row-level, volatile drift).

  keyed-diff --lake-a A --lake-b B --models public_models.yaml TABLE [TABLE...]
      EXCEPT ALL both ways on the non-volatile columns, with sample keys.

Fingerprints are order-independent: per column count/bit_xor(hash)/sum(hash) and per row
bit_xor/sum of hash(all non-volatile columns), so swapping values between rows is caught.
Floating columns are rounded to 6 decimals before hashing.
"""
from __future__ import annotations

import argparse
import datetime as dt
import glob
import json
import os
import sys

import duckdb
import yaml

ROLLING_REL = os.path.join("export", "marts", "rolling")
WAREHOUSE = "sapo_warehouse.duckdb"
FLOAT_TYPES = {"DOUBLE", "FLOAT", "REAL"}
NUMERIC_PREFIXES = ("DOUBLE", "FLOAT", "REAL", "DECIMAL", "HUGEINT", "BIGINT", "INTEGER", "SMALLINT", "TINYINT", "UBIGINT", "UINTEGER")

# Relations without a rolling location that consumers outside dbt read directly
# (crm/, tools/), found by searching those trees for model names.
EXTRA_RELATIONS = [
    "dim_customers_base",
    "int_customer_metrics",
    "int_customer_economics",
    "int_customer_entry_attributes",
    "int_customer_sku_supply_tracking",
    "int_customer_discount_metrics",
    "int_crm_outreach_effort_events",
    "mart_hug_optin",
    "dim_fb_ads",
    "fact_fb_ads_insights_daily",
    "dim_fb_conversations",
    "fact_fb_messages",
]


def q(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


# ---------------------------------------------------------------- init
def cmd_init(args: argparse.Namespace) -> int:
    manifest = json.load(open(args.manifest))
    nodes = manifest["nodes"]
    models = {n["name"]: n for n in nodes.values() if n["resource_type"] == "model"}

    keys: dict[str, list[str]] = {}
    for n in nodes.values():
        if n["resource_type"] != "test":
            continue
        meta = n.get("test_metadata") or {}
        attached = [d for d in n.get("depends_on", {}).get("nodes", []) if d.startswith("model.")]
        if len(attached) != 1:
            continue
        model = attached[0].split(".")[-1]
        kw = meta.get("kwargs") or {}
        if meta.get("name") == "unique" and kw.get("column_name"):
            keys.setdefault(model, [kw["column_name"]])
        elif meta.get("name") == "unique_combination_of_columns" and kw.get("combination_of_columns"):
            keys[model] = list(kw["combination_of_columns"])

    tables: dict[str, dict] = {}
    for name, n in sorted(models.items()):
        if not n.get("config", {}).get("enabled", True):
            continue
        loc = str(n.get("config", {}).get("location") or "")
        if n["config"].get("materialized") == "external" and ("get_rolling_location" in loc or "/rolling/" in loc):
            tables[name] = {"kind": "rolling"}
    for name in EXTRA_RELATIONS:
        if name in models and name not in tables:
            n = models[name]
            mat = n["config"]["materialized"]
            kind = "external" if mat == "external" else "relation"
            tables[name] = {"kind": kind, "schema": n["schema"], "materialized": mat}
    for name in tables:
        tables[name]["unique_id"] = models[name]["unique_id"]
        if name in keys:
            tables[name]["key"] = keys[name]

    previous = yaml.safe_load(open(args.out)) if os.path.exists(args.out) else {}
    doc = {
        "description": "Public tables whose data must not change during refactors. "
        "Generated by golden_snapshot.py init; edit volatile_columns by hand with a reason.",
        "tables": tables,
        "volatile_columns": (previous or {}).get("volatile_columns") or {},
    }
    if (previous or {}).get("volatile_reason"):
        doc["volatile_reason"] = previous["volatile_reason"]
    with open(args.out, "w") as fh:
        yaml.safe_dump(doc, fh, sort_keys=False, allow_unicode=True)
    print(f"wrote {args.out}: {len(tables)} tables ({sum(1 for t in tables.values() if 'key' in t)} with key)")
    return 0


# ---------------------------------------------------------------- capture
def _latest_parquet(lake: str, name: str) -> str | None:
    files = sorted(glob.glob(os.path.join(lake, ROLLING_REL, name, "*.parquet")))
    return files[-1] if files else None


def _source_sql(con, lake: str, name: str, spec: dict) -> tuple[str, str | None]:
    if spec["kind"] == "rolling":
        path = _latest_parquet(lake, name)
        if not path:
            return "", None
        return f"read_parquet('{path}')", path
    if spec["kind"] == "external":
        # dbt-duckdb default external path: <external_root>/<name>.parquet. Read the file
        # relative to the lake instead of the warehouse view, whose path is absolute.
        path = os.path.join(lake, "export", "marts", f"{name}.parquet")
        return (f"read_parquet('{path}')", path) if os.path.exists(path) else ("", None)
    return f"wh.{q(spec['schema'])}.{q(name)}", None


def _describe(con, src: str) -> list[tuple[str, str]]:
    return [(r[0], r[1]) for r in con.execute(f"DESCRIBE SELECT * FROM {src}").fetchall()]


def _expr(col: str, typ: str) -> str:
    return f"round({q(col)}, 6)" if typ.upper() in FLOAT_TYPES else q(col)


def fingerprint(con, src: str, volatile: list[str]) -> dict:
    cols = _describe(con, src)
    stable = [(c, t) for c, t in cols if c not in volatile]
    parts = ["count(*)"]
    for c, t in stable:
        e = _expr(c, t)
        parts += [f"count({q(c)})", f"bit_xor(hash({e}))", f"sum(hash({e})::HUGEINT)"]
    if stable:
        row = ", ".join(_expr(c, t) for c, t in stable)
        parts += [f"bit_xor(hash({row}))", f"sum(hash({row})::HUGEINT)"]
    vol_parts = []
    for c, t in cols:
        if c in volatile:
            if t.upper().startswith(NUMERIC_PREFIXES):
                vol_parts.append(f"sum({q(c)})::DOUBLE")
            else:
                vol_parts.append(f"count({q(c)})")
    res = con.execute(f"SELECT {', '.join(parts + vol_parts)} FROM {src}").fetchone()
    i = 1
    percol = {}
    for c, _ in stable:
        percol[c] = [res[i], str(res[i + 1]), str(res[i + 2])]
        i += 3
    rowfp = [str(res[i]), str(res[i + 1])] if stable else []
    i += 2 if stable else 0
    vol = {}
    for c, _ in [(c, t) for c, t in cols if c in volatile]:
        vol[c] = res[i]
        i += 1
    return {"rows": res[0], "columns": cols, "percol": percol, "row": rowfp, "volatile": vol}


def _load_meta(lake: str) -> tuple[dt.datetime, dict]:
    meta = os.path.join(lake, "_shadow_meta")
    start = open(os.path.join(meta, "build_start")).read().strip()
    start_dt = dt.datetime.strptime(start, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=dt.timezone.utc)
    rr = json.load(open(os.path.join(meta, "run_results.json")))
    status = {r["unique_id"]: r["status"] for r in rr.get("results", [])}
    return start_dt, status


def cmd_capture(args: argparse.Namespace) -> int:
    spec = yaml.safe_load(open(args.models))
    tables, volatile = spec["tables"], spec.get("volatile_columns") or {}
    start_dt, status = _load_meta(args.lake)
    con = duckdb.connect()
    con.execute(f"ATTACH '{os.path.join(args.lake, WAREHOUSE)}' AS wh (READ_ONLY)")
    out, errors = {}, []
    for name, t in tables.items():
        st = status.get(t["unique_id"])
        if st != "success":
            errors.append(f"{name}: run_results status={st!r} (not rebuilt in this build)")
        src, path = _source_sql(con, args.lake, name, t)
        if not src:
            errors.append(f"{name}: no parquet output found")
            continue
        if path:
            mtime = dt.datetime.fromtimestamp(os.path.getmtime(path), tz=dt.timezone.utc)
            if mtime < start_dt:
                errors.append(f"{name}: newest parquet {os.path.basename(path)} predates build start")
        try:
            out[name] = fingerprint(con, src, list(volatile.get(name, {}) or []))
        except Exception as exc:  # report every table, do not stop at the first failure
            errors.append(f"{name}: fingerprint error {exc}")
    doc = {"lake": args.lake, "build_start": start_dt.isoformat(), "tables": out, "errors": errors}
    with open(args.out, "w") as fh:
        json.dump(doc, fh, indent=1, default=str)
    for e in errors:
        print("STALE/ERROR", e)
    print(f"captured {len(out)}/{len(tables)} tables -> {args.out}; {len(errors)} error(s)")
    return 1 if errors else 0


# ---------------------------------------------------------------- compare
def cmd_compare(args: argparse.Namespace) -> int:
    a, b = json.load(open(args.a)), json.load(open(args.b))
    diffs = []
    for side, doc in (("A", a), ("B", b)):
        for e in doc.get("errors", []):
            diffs.append(f"[{side} capture error] {e}")
    ta, tb = a["tables"], b["tables"]
    for name in sorted(set(ta) | set(tb)):
        if name not in ta or name not in tb:
            diffs.append(f"{name}: only in {'A' if name in ta else 'B'}")
            continue
        x, y = ta[name], tb[name]
        if x["rows"] != y["rows"]:
            diffs.append(f"{name}: rows {x['rows']} -> {y['rows']}")
        if x["columns"] != y["columns"]:
            diffs.append(f"{name}: schema differs {x['columns']} -> {y['columns']}")
        bad_cols = [c for c in x["percol"] if c in y["percol"] and x["percol"][c] != y["percol"][c]]
        if bad_cols:
            diffs.append(f"{name}: column values differ: {bad_cols}")
        if x["row"] != y["row"] and not bad_cols:
            diffs.append(f"{name}: row-level fingerprint differs (values moved between rows)")
        for c, va in x.get("volatile", {}).items():
            vb = y.get("volatile", {}).get(c)
            if isinstance(va, (int, float)) and isinstance(vb, (int, float)):
                tol = max(abs(va), abs(vb), 1.0) * args.rel_tol
                if abs(va - vb) > tol:
                    diffs.append(f"{name}: volatile numeric {c} drift {va} -> {vb}")
    for d in diffs:
        print("DIFF", d)
    print(f"compare: {len(ta)} vs {len(tb)} tables, {len(diffs)} difference(s)")
    return 1 if diffs else 0


# ---------------------------------------------------------------- keyed diff
def cmd_keyed_diff(args: argparse.Namespace) -> int:
    spec = yaml.safe_load(open(args.models))
    volatile = spec.get("volatile_columns") or {}
    con = duckdb.connect()
    con.execute(f"ATTACH '{os.path.join(args.lake_a, WAREHOUSE)}' AS wh (READ_ONLY)")
    con.execute(f"ATTACH '{os.path.join(args.lake_b, WAREHOUSE)}' AS whb (READ_ONLY)")
    rc = 0
    for name in args.tables:
        t = spec["tables"][name]
        src_a, _ = _source_sql(con, args.lake_a, name, t)
        src_b, _ = _source_sql(con, args.lake_b, name, t)
        src_b = src_b.replace("wh.", "whb.", 1)
        cols = [c for c, _ in _describe(con, src_a) if c not in (volatile.get(name) or [])]
        sel = ", ".join(q(c) for c in cols)
        key = ", ".join(q(c) for c in t.get("key", cols[:3]))
        for label, s1, s2 in (("A-B", src_a, src_b), ("B-A", src_b, src_a)):
            n = con.execute(f"SELECT count(*) FROM (SELECT {sel} FROM {s1} EXCEPT ALL SELECT {sel} FROM {s2})").fetchone()[0]
            if n:
                rc = 1
                sample = con.execute(f"SELECT {key} FROM (SELECT {sel} FROM {s1} EXCEPT ALL SELECT {sel} FROM {s2}) LIMIT 5").fetchall()
                print(f"{name} {label}: {n} rows, sample keys {sample}")
            else:
                print(f"{name} {label}: 0 rows")
    return rc


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("init"); s.add_argument("--manifest", required=True); s.add_argument("--out", required=True)
    s = sub.add_parser("capture"); s.add_argument("--lake", required=True); s.add_argument("--models", required=True); s.add_argument("--out", required=True)
    s = sub.add_parser("compare"); s.add_argument("a"); s.add_argument("b"); s.add_argument("--rel-tol", type=float, default=1e-9)
    s = sub.add_parser("keyed-diff"); s.add_argument("--lake-a", required=True); s.add_argument("--lake-b", required=True)
    s.add_argument("--models", required=True); s.add_argument("tables", nargs="+")
    args = p.parse_args()
    return {"init": cmd_init, "capture": cmd_capture, "compare": cmd_compare, "keyed-diff": cmd_keyed_diff}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
