#!/usr/bin/env bash
# Report site builder: build every Evidence area into a new directory and switch it in atomically.
#
# Runs as the command of the `evidence` container (it serves nothing; container `report_site`
# serves app_data/report_site/<area>/current behind per-area login).
#
#   build-areas.sh            loop: on start, build only the areas that have no `current` yet (a
#                             restart does not rebuild); then every $POLL_SECONDS look for a new
#                             request (request.json written by Dagster after the nightly run) and
#                             build all areas once per request_id
#   build-areas.sh --once     build all areas now and exit (manual run)
#
# Areas: every directory under $AREAS_DIR (generated by `python3 -m analytics render evidence`,
# base path /<area>) plus `legacy` = the hand-written project in $LEGACY_DIR (pages/, sources/,
# evidence.config.yaml; served at the root). Each area is built sequentially in a scratch copy
# under $WORK_DIR, with $AREA_TIMEOUT seconds; a failed area keeps its previous build.
#
# Output: $SITE_DIR/<area>/builds/<build_id>/, symlink $SITE_DIR/<area>/current (swapped with
# rename, never half-written), $KEEP_BUILDS kept. $REQUEST_DIR/status.json records the outcome of
# the last run per area. Runbook: evidence/README.md ("Report site").
set -uo pipefail

AREAS_DIR="${AREAS_DIR:-/app/areas}"
LEGACY_DIR="${LEGACY_DIR:-/app}"
SITE_DIR="${SITE_DIR:-/app/site}"
REQUEST_DIR="${REQUEST_DIR:-/app/var/report_build}"
OLAP_DB="${OLAP_DB:-/app/var/data_lake/serving/olap.duckdb}"
NODE_MODULES="${NODE_MODULES:-/app/node_modules}"
PACKAGE_JSON="${PACKAGE_JSON:-/app/package.json}"
WORK_DIR="${WORK_DIR:-/tmp/report-build}"
EVIDENCE_CMD="${EVIDENCE_CMD:-npx --no-install evidence}"
AREA_TIMEOUT="${AREA_TIMEOUT:-1200}"
POLL_SECONDS="${POLL_SECONDS:-60}"
HEARTBEAT="${HEARTBEAT:-/tmp/build-areas.heartbeat}"  # touched every loop; container healthcheck
KEEP_BUILDS="${KEEP_BUILDS:-3}"
OUT_SUBDIR=build   # Evidence writes the static site to ./build of the project

log() { echo "[build-areas] $(date '+%F %T') $*"; }

areas() {
  local d
  for d in "$AREAS_DIR"/*/; do
    [ -f "$d/evidence.config.yaml" ] && basename "$d"
  done
  [ -d "$LEGACY_DIR/pages" ] && echo legacy
}

project_src() {  # where the sources of an area live
  if [ "$1" = legacy ]; then echo "$LEGACY_DIR"; else echo "$AREAS_DIR/$1"; fi
}

# build_area <area> <build_id>: 0 on success; prints the error line on failure
build_area() {
  local area="$1" id="$2" src work dest
  src="$(project_src "$area")"
  work="$WORK_DIR/$area"
  rm -rf "$work" && mkdir -p "$work" || { echo "cannot create $work"; return 1; }
  cp -r "$src/pages" "$src/sources" "$src/evidence.config.yaml" "$work/" || { echo "cannot copy $src"; return 1; }
  cp "$PACKAGE_JSON" "$work/package.json" && ln -sfn "$NODE_MODULES" "$work/node_modules" || { echo "cannot link node_modules"; return 1; }
  cp "$OLAP_DB" "$work/sources/datalake/olap-serving.duckdb" || { echo "cannot copy $OLAP_DB"; return 1; }
  if ! (cd "$work" && timeout "$AREA_TIMEOUT" sh -c "$EVIDENCE_CMD sources && $EVIDENCE_CMD build") > "$work.log" 2>&1; then
    echo "evidence sources/build failed or timed out after ${AREA_TIMEOUT}s: $(tail -n 3 "$work.log" | tr '\n' ' ' | cut -c1-300)"
    return 1
  fi
  [ -f "$work/$OUT_SUBDIR/index.html" ] || { echo "no index.html in the output"; return 1; }
  # Default theme dark instead of system (was step 4 of the old container command)
  find "$work/$OUT_SUBDIR" -name '*.html' -exec sed -i "s/?? 'system'/?? 'dark'/g" {} +
  dest="$SITE_DIR/$area/builds/$id"
  mkdir -p "$SITE_DIR/$area/builds" && rm -rf "$dest" && mv "$work/$OUT_SUBDIR" "$dest" || { echo "cannot move output to $dest"; return 1; }
  ln -sfn "builds/$id" "$SITE_DIR/$area/current.new" && mv -Tf "$SITE_DIR/$area/current.new" "$SITE_DIR/$area/current" \
    || { echo "cannot switch current"; return 1; }
  # keep the newest $KEEP_BUILDS builds (build ids sort by time)
  ls -1 "$SITE_DIR/$area/builds" | sort | head -n -"$KEEP_BUILDS" | while read -r old; do
    rm -rf "${SITE_DIR:?}/$area/builds/$old"
  done
  rm -rf "$work" "$work.log"
  return 0
}

json_escape() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }

# run_build <request_id> <area...>: builds the areas and writes status.json
run_build() {
  local request_id="$1"; shift
  local id started as_of entries="" area t0 err ok all_ok=true
  id="$(date '+%Y%m%dT%H%M%S')"
  started="$(date -Iseconds)"
  as_of="$(date -d yesterday '+%F')"
  for area in "$@"; do
    t0=$(date +%s)
    log "area $area: building ($id)"
    if err="$(build_area "$area" "$id")"; then ok=true; err=""; log "area $area: ok"
    else ok=false; all_ok=false; log "area $area: FAILED: $err (previous build kept)"; fi
    entries+="${entries:+,}\"$area\":{\"ok\":$ok,\"build_id\":\"$id\",\"duration_s\":$(( $(date +%s) - t0 )),\"error\":\"$(json_escape "$err")\"}"
  done
  mkdir -p "$REQUEST_DIR"
  printf '{"request_id":"%s","started_at":"%s","finished_at":"%s","as_of":"%s","ok":%s,"areas":{%s}}\n' \
    "$(json_escape "$request_id")" "$started" "$(date -Iseconds)" "$as_of" "$all_ok" "$entries" \
    > "$REQUEST_DIR/status.json.tmp" && mv -f "$REQUEST_DIR/status.json.tmp" "$REQUEST_DIR/status.json"
  $all_ok
}

request_id() {  # request_id of $REQUEST_DIR/request.json, empty when absent
  [ -f "$REQUEST_DIR/request.json" ] || return 0
  sed -n 's/.*"request_id"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$REQUEST_DIR/request.json" | head -n 1
}

main() {
  mkdir -p "$SITE_DIR" "$WORK_DIR" || exit 1
  exec 9>"$SITE_DIR/.build.lock"
  if ! flock -n 9; then log "another build is running; exiting"; exit 1; fi
  mapfile -t ALL < <(areas)
  [ "${#ALL[@]}" -gt 0 ] || { log "no area to build in $AREAS_DIR or $LEGACY_DIR"; exit 1; }

  if [ "${1:-}" = "--once" ]; then
    run_build "manual-$(date '+%Y%m%dT%H%M%S')" "${ALL[@]}"
    exit $?
  fi

  local missing=() area
  for area in "${ALL[@]}"; do [ -e "$SITE_DIR/$area/current" ] || missing+=("$area"); done
  if [ "${#missing[@]}" -gt 0 ]; then
    log "first build for areas without current: ${missing[*]}"
    run_build "initial" "${missing[@]}"
    # the data of any pending request is already in this build
    request_id > "$SITE_DIR/.last_request_id"
  else
    log "current exists for every area (${ALL[*]}); waiting for a build request"
  fi
  # A request already handled before this start is not rebuilt.
  local last; last="$(cat "$SITE_DIR/.last_request_id" 2>/dev/null || true)"
  while true; do
    touch "$HEARTBEAT"
    local rid; rid="$(request_id)"
    if [ -n "$rid" ] && [ "$rid" != "$last" ]; then
      mapfile -t ALL < <(areas)
      log "build request $rid"
      run_build "$rid" "${ALL[@]}"
      last="$rid"; printf '%s\n' "$rid" > "$SITE_DIR/.last_request_id"
    fi
    sleep "$POLL_SECONDS"
  done
}

main "$@"
