"""Render the Caddyfile of the report site (container `report_site`) from the tenant's access areas.

  python3 -m analytics render site --tenant fine_japan [--check]   -> evidence/site/Caddyfile

One path per area, each with its own `basic_auth` whose accounts (one per person) are imported from
/etc/caddy/users/<area>.caddy (mounted from app_data/secrets/report_site/, never in git; managed with
evidence/site/report-users.sh). A missing or empty users file makes Caddy refuse to start, so an area
is never served without login. The legacy area (hand-written pages, no base path) answers every other
path; without a legacy area those paths get 404.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

from ..compiler.loader import REPO_ROOT

OUT_FILE = REPO_ROOT / "evidence" / "site" / "Caddyfile"
USERS_DIR = "/etc/caddy/users"
SITE_ROOT = "/srv"
LISTEN = ":8080"


def _serve(area_id: str) -> list[str]:
    return [
        f"\t\tbasic_auth {{",
        f"\t\t\timport {USERS_DIR}/{area_id}.caddy",
        f"\t\t}}",
        f"\t\troot * {SITE_ROOT}/{area_id}/current",
        "\t\ttry_files {path} {path}.html {path}/index.html",
        "\t\tfile_server",
    ]


def render_caddyfile(profile: dict[str, Any]) -> str:
    areas = (profile.get("access") or {}).get("areas", [])
    lines = [
        "# GENERATED by `python3 -m analytics render site` from the tenant profile (access.areas).",
        "# Do not edit by hand. Accounts: evidence/site/report-users.sh; runbook: evidence/README.md.",
        "{",
        "\tadmin localhost:2019",
        "}",
        "",
        f"{LISTEN} {{",
        "\t# Access log names the signed-in user (user_id) of every request.",
        "\tlog {",
        "\t\toutput stdout",
        "\t\tformat json",
        "\t}",
        "\theader -Server",
        "\theader Cache-Control \"private, no-store\"",
        "",
    ]
    legacy = None
    for area in areas:
        if area.get("legacy"):
            legacy = area
            continue
        aid = area["id"]
        lines += [
            f"\t# {area['title']} (can_view_cost: {str(area['can_view_cost']).lower()})",
            f"\tredir /{aid} /{aid}/ 308",
            f"\thandle_path /{aid}/* {{",
            *_serve(aid),
            "\t}",
            "",
        ]
    if legacy:
        lines += [f"\t# {legacy['title']}: every other path", "\thandle {", *_serve(legacy["id"]), "\t}"]
    else:
        lines += ["\thandle {", "\t\trespond 404", "\t}"]
    lines.append("}")
    return "\n".join(lines) + "\n"


def write(content: str, out_file: Path = OUT_FILE) -> bool:
    if out_file.exists() and out_file.read_text(encoding="utf-8") == content:
        return False
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(content, encoding="utf-8")
    return True
